p("本文把分块频域重采样在任意有理倍率下的误差收敛到四个可分别处理的环节：频域网格、块接缝、文件边界与浮点舍入。前两个由 P=M·s、Q=L·s 与 M 的整数倍步进解决，第三个由 20 ms 五次 smootherstep 窗解决，第四个构成测量地板。四者合起来把九种倍率的零差推到 300.9–303.8 dB，与 PGGB 的 302.0 dB 处于同一地板。")
