h1("4  测量协议")
h2("4.1  激励、参考与聚合")
p("零差测试比较转换输出与解析参考。参考信号按 (f·n) mod f_{s} 递推相位，避免 sin(2πft) 在 18 kHz、4 s 时累积 4.5×10^{5} rad 的相位误差；后者在 float64 下本身就是 −257 dBc，会把被测对象的地板误读成 217 dB。激励取 16 s；分析取 5 个互不重叠的 1 s 窗，取中位数。")
p("激励长度由边界效应决定。4 s 激励时 20 ms 渐变占 0.5%，边界效应会把读数压低 5–9 dB；16 s 把这一项降到 0.125%，单窗摆动则被中位数压住。所有测试信号为整数相位、整数频率的正弦或正弦和，分析窗为矩形窗且取整数个周期，以避免泄漏。")

h2("4.2  零差与增益精修")
p("零差（null depth）衡量转换输出与参考之间还剩多少残差。记输出为 y[n]，参考为 r[n]，两者长度均为 N；内积与范数取分析区间上的样本和，⟨a,b⟩=Σ a[n]b[n]，‖a‖=√⟨a,a⟩。先估计一个只含幅度、不含时延的实增益 g，使 g·r 在最小二乘意义下最接近 y：")
p("闭式解 g=⟨y,r⟩/⟨r,r⟩ 是归一化最小二乘的解[23]，只精确到几个最小浮点单位（ulp），误差不是二阶的。对把峰值归一化到 0.99 的 PGGB，它会把零差低估 13 dB（288.8 对 302.0 dB）。本文用三步 Gauss–Newton 精修，迭代格式为")
eq("g_{0} = ⟨y,r⟩/⟨r,r⟩，  g_{i+1} = g_{i} + ⟨y−g_{i}r, r⟩/⟨r,r⟩", 4)
p("式 (4) 中 i=0,1,2，共三步；每步只更新一个标量，计算量可以忽略。这里不估计时延：各引擎的输出按同一采样网格对齐，时延差异会作为残差留在 D 中，而不是被增益吸收。")
p("测量区间同样影响增益。若在 4 s 全文件上估计，读数会比真实值低 0.5%（0.4975 对 0.5000），因为首尾各 20 ms 的渐变占 1% 时长、平均窗值为 0.5。把区间移到内部后，增益回到 1.000000。该 0.5% 来自渐变窗的均值效应，并非引擎的全局增益误差。")
p("零差定义为增益精修后的残差范数与参考范数之比：")
eq("D = −20 lg( ‖y−g_{3}r‖ / ‖r‖ )", 5)
p("式 (5) 是本文的定义，不是 AES17 或 IEC 60268-3 的规定量；后两者只约束 dBFS 与互调激励。D 为正值，越大表示越接近参考；float64 的 FFT 舍入把 D 限制在 302 dB 附近。")
p("真实音乐没有解析参考，不能直接套用式 (5)。设 y_{ref} 为同一引擎对 120 s 整段输入的一次转换，y_{chunk} 为同一引擎按 16 s 分块、逐块转换后按序拼接的输出；对每个通道分别计算")
eq("D_{chunk} = −20 lg( ‖y_{chunk}−g y_{ref}‖ / ‖y_{ref}‖ )", 6)
p("式 (6) 中的 g 仍按式 (4) 估计。计算时去掉两段信号首尾各 10% 的样本，以避开文件边界；报告最差通道。D_{chunk} 衡量的是“分块是否改变了该引擎自己的整段结果”，不是与原始音乐比较，也不是相邻块之间的差异。它不能跨引擎读成“接近原音”的程度；不同引擎的整段结果本来就不同。")

h2("4.3  指标定义")
p("本节把六项失真指标全部写成输出频谱的函数；图 2c、2d 给出这些读数在频域中的位置。除零差外，各项均以 dBc 表示：dBc 的分母是实测基频幅度 A_{f0}，不是满量程；dBFS 的分母才是满量程，按 AES17[11] 的表述约定。这个区分在 −300 dBc 量级尤其重要，因为分母选错 0.5 dB，读数就会偏 0.5 dB。")
p("杂散。输入 1 kHz、0.5 满量程单音，44.1→88.2 kHz；取 5 个互不重叠的 1 s 窗，每窗为整数个周期，因此不需要窗函数。设 Y[k] 为某窗的 rFFT，T 为基频 ±3 个 bin 的集合；扣除 T 后的残余能量与 T 内能量之比为")
eq("D_{spur} = 10 lg( Σ_{k∉T}|Y[k]|^{2} / Σ_{k∈T}|Y[k]|^{2} )", 7)
p("式 (7) 等价于先对基频做幅度、相位自由的最小二乘拟合，再取残差 RMS 与拟合音 RMS 之比；分母是拟合音能量，不是单根谱线。T 之外的直流分量不计入残余。早期口径只扣一根 bin，会把基频的泄漏裙边读成杂散：1 kHz 音的最差“杂散”落在 993 Hz，比真实值高 3 dB。")
p("镜像。44.1→88.2 kHz 时，1 kHz 的镜像落在 f_{img}=f_{s}−f_{0}=43.1 kHz，位于输出奈奎斯特 44.1 kHz 之下。镜像不是一根干净的线，而是从 f_{img} 到输出奈奎斯特的一整片。记该频带为 B=[f_{img}, f_{s}′/2]，带内能量 E_{img}=Σ_{f∈B}|Y(f)|^{2}，则")
eq("D_{image} = 10 lg( E_{img} / (A_{f0}^{2}/2) )", 8)
p("式 (8) 的分母取输出中实测的基频幅度 A_{f0}，不用标称的 0.5 满量程。PGGB 把峰值归一化到 0.99，固定分母会人为引入 6 dB 偏差。")
p("混叠。96→44.1 kHz，输入为 1 kHz 参考音与 30 kHz 侵略音，各 0.5 满量程；30 kHz 折叠到 f_{alias}=|30−round(30/44.1)×44.1|=14.1 kHz。混叠读单根折叠 bin 的幅度，除以 1 kHz 参考音的实测幅度：")
eq("f_{alias} = |f_{a} − round(f_{a}/f_{s}′) f_{s}′|，  D_{alias} = 20 lg( A_{fold}/A_{f0} )", 9)
p("参考音必须在场。只送孤立阻带音时，sox_ng 返回逐位全零，分母为 0，读数成了 −394 dBc；这不是抑制能力，是 0/0。双音口径下它的真实值是 −221.0 dBc。")
p("CCIF 互调。输入 19 kHz 与 20 kHz 双音，各 0.25 满量程；取二阶与三阶产物 2f_{1}−f_{2}、2f_{2}−f_{1}、f_{2}−f_{1}、f_{1}+f_{2} 中最差的一个：")
eq("D_{CCIF} = 20 lg( A_{prod}^{max} / √(A_{f1}A_{f2}) )", 10)
p("式 (10) 中 P_{CCIF}={2f_{1}−f_{2}, 2f_{2}−f_{1}, f_{2}−f_{1}, f_{1}+f_{2}}，A_{f1}、A_{f2} 为两音实测幅度，分母取几何平均。几何平均使某个音被过渡带削掉时，分子与分母同步下降，不会把“把音滤掉了”误判成“互调很低”。")
p("SMPTE 互调。60 Hz 低频音 0.40 满量程、7 kHz 高频音 0.10 满量程，幅度比 4:1；读 7 kHz 的 ±60、±120 Hz 边带中最差的一个，除以 7 kHz 实测幅度：")
eq("D_{SMPTE} = 20 lg( A_{side}^{max} / A_{f2} )", 11)
p("多音。24 个对数间隔的等幅音覆盖 100 Hz–18 kHz，Schroeder 相位（二次相位分布，压低峰均比）、峰值 0.9；仍按式 (7) 扣除各音 ±3 bin 后取残余，只是把 T 换成 24 个音的 bin 集合 U：")
eq("D_{mt} = 10 lg( Σ_{k∉U}|Y[k]|^{2} / Σ_{k∈U}|Y[k]|^{2} )", 12)
p("以上各项均在 5 个 1 s 窗上计算后取中位数；单窗结果受接缝位置影响可摆动 5–10 dB。互调的激励与归一化沿用 IEC 60268-3[24] 与 SMPTE RP 120[25]，但两项标准规定的是测量条件，不规定 −300 dBc 量级的读出方式；式 (7)–(12) 的读出量由本文定义。")
p("单音三项。SINAD、SFDR 与 ENOB 借自模数转换器测试[26]。在 −300 dB 量级上，这三个量对分母与带宽的取值比对引擎更敏感，口径须先固定。设基频幅度为 A_{f0}，残差 r 为输出减去拟合出的 c + A_{f0}cos(2πf_{0}t+φ) 之后的部分（c 为拟合直流，不计入噪声），则")
eq("D_{SINAD} = 10 lg( (A_{f0}^{2}/2) / (Σr^{2}/N) )", 13)
p("式 (13) 的分母是残差的全带功率，按 Parseval 等价于 Σr^{2}/N，谐波、杂散、镜像与宽带噪声都在其中；分子是基频功率，不是满量程功率。SFDR 只取最坏的一根谱线，除直流与基频 ±1 bin 外最大幅度为 A_{spur}^{max}，与基频之比为")
eq("D_{SFDR} = 20 lg( A_{f0} / A_{spur}^{max} )", 14)
p("窗长取整数个周期，矩形窗无泄漏，bin 幅度即真实幅度，不做窗函数修正。ENOB 按满刻度正弦折算：测试音 0.5 满量程时 D_{SINAD}^{FS} = D_{SINAD} + 6.02 dB。")
eq("ENOB = (D_{SINAD}^{FS} − 1.76)/6.02", 15)
p("这三项不能用 rFFT 的 bin 能量相减得到。输出的量化步长本身在 −320 dBc；rFFT 的基函数只有 1e-16 的相对精度，求和误差又在 √N·ε 量级，扣 bin 法的地板落在 −290…−307 dBc，与被测引擎同量级（§4.4）。这种读法测的是尺子，不是引擎。")
p("本文改用残差法：基函数按整数相位 θ_{n}=2π((kn) mod N)/N 以 60 位有效数字预计算，投影用双倍长累加，减掉拟合音后再对残差投影一次，扣去模型自身的舍入。地板由此降到 SINAD 328.3 dB、ENOB 55.2 bit，即把 50 位有效数字的正弦舍入成 float64 后读到的值。注入 −60、−100、−140 dBc 的已知单音，读数与解析值逐位一致；同一段 sox_ng 输出用扣 bin 法与残差法各算一次，差 0.02 dB。在 −300 dB 附近，读数由引擎决定。")

