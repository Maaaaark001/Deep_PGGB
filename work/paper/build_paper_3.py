h1("6  讨论")
h2("6.1  什么在限制精度")
p("本文的全部实验指向同一个结论：在 −300 dB 这个量级上，限制精度的不是滤波器设计，而是三件事——"
  "浮点运算的舍入（float64 的 2^-53）、参考信号的生成方式、以及文件的边界。"
  "前两者可以消除：整数相位递推把参考信号的自身误差从 −217 dB 压到 −323 dB，"
  "long double 变体则在 6 音测试中把舍入地板再推低约 6 dB（309.6 dB）。"
  "第三者无法消除，只能推远：把渐变窗从 C^2 提高到 C^5，边界旁瓣从 −259.8 dB 压到 −355.7 dB，"
  "落点也从 22.05 kHz 推到 21.9 kHz 以上。")
p("修正之前，本文观察到一个稳定但无法解释的方向性：降采样方向总是 302–303 dB，"
  "升采样方向却只有 301.7 dB。现在的解释是，升采样时输出网格包含源奈奎斯特这个频点，"
  "而它正是渐变窗旁瓣的落点；降采样时该频点被丢弃，残留随之消失。"
  "把窗提高到 C^5 之后，两侧同时到达 300.9–303.8 dB 的地板（表 4），方向性消失——"
  "这反过来证明此前的差异确实来自窗，而不是来自算法的方向性偏好。")

h2("6.2  300 dB 有什么意义")
p("24 bit 音频的量化噪声约为 −144 dBFS，32 bit 浮点约为 −192 dBFS，而人耳的听觉动态范围约 120 dB。"
  "在这个背景下，300 dB 的零差深度显然没有直接的可闻意义。它的价值在于两点。")
p("第一，它给出了\"算法本身没有引入误差\"的确证。当一个引擎的零差达到 300 dB，"
  "意味着输出与理想解之间的差异已经小于浮点表示的分辨率——"
  "此时任何进一步的质量提升都不可能来自重采样环节，而只能来自素材、量化或后处理。"
  "这对母带处理是有意义的：它把\"SRC 是不是瓶颈\"这个问题从猜测变成可测量的判断。")
p("第二，它让不同引擎之间的比较变得有意义。在 −200 dB 的量级上，两个引擎的差异可能来自过渡带设计；"
  "在 −300 dB 的量级上，差异只可能来自算法结构（例如是否支持任意倍率）。"
  "本文因此可以明确地说：Deep_PGGB 与 PGGB 在精度上不可区分，区别在功能（任意倍率）与速度（约 3.9 倍）。")

h2("6.3  局限")
p("(1) 本文的所有精度数字都建立在\"带限激励 + 解析参考\"之上。对于真实音乐素材，"
  "参考解无法解析给出，只能做引擎间的零差，而那种零差反映的是两条处理链的差异，"
  "不是与理想解的差异。本文因此没有对真实素材声称 300 dB。")
p("(2) 距离源奈奎斯特 100 Hz 以内的精度受边界处理主导，Deep_PGGB 与 PGGB 都在 55–140 dB 量级。"
  "这个区间对 DSD 转 PCM 等应用是相关的，本文没有给出更好的方案。")
p("(3) 速度数据依赖具体硬件。本文的所有吞吐量数字来自同一台机器（Windows 11、"
  "MSYS2 UCRT64 g++ 16.2、FFTW 3.3.10），跨平台比较需要重新测量。")
p("(4) 与商业工具（Weiss Saracon、iZotope RX、HQPlayer）的对比无法进行，因为它们不提供可驱动的内核，"
  "只能依据厂商口径，不构成可比证据。")
p("(5) 八引擎对比表里的 21.5 kHz 一列是升采样口径（44.1→96 kHz，纯砖墙、无滚降），"
  "因此 Deep_PGGB 与 SSRC 读作 0.00 dB；降采样时默认滚降会让 21.9 kHz 以下才开始下垂。"
  "同一列里 sox_ng 与 libsoxr 的 −32 dB 是它们自身的通带上限，与滚降无关。")
p("(6) 表 6 的五列里有三项贴在地板上，而地板是由 float64 的 FFT 舍入决定的。"
  "这意味着那三列只能给出\"不高于某个电平\"的结论，不能给出排序：同一台引擎换一个"
  "不影响数学结果的旋钮（块长 16 秒改 4 秒、激励 16 秒改 4 秒），读数就会摆动 5–9 dB，"
  "与引擎之间的差值同量级。本文因此把这三列的结论表述为\"都在 −300 dBc 以下\"，"
  "而不是\"谁比谁高几 dB\"。只有混叠一列远离地板，它的排序是稳定的。"
  "同理，表 6 的协议（16 秒激励、5 个 1 秒窗中位数、块长 16 秒）必须在表注里写死，"
  "否则同一批引擎换一套协议就能换一个名次。")
p("(7) 本文修正了两项此前被广泛使用（包括本文早期版本自己）的测量口径：杂散的单根谱线口径"
  "会读到基频的窗泄漏，混叠的孤立阻带单音口径会遇到除以零。修正后，多台引擎的读数变化超过 100 dB，"
  "这提醒任何跨引擎的\"抑制能力\"排名都必须先公布口径；本文把全部激励、窗长与分母都写进了 4.5 与 4.6 节。")

