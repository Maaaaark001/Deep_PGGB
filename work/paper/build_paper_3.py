h1("7  结论")
p("本文提出了 Deep_PGGB，一种以精确有理倍率实现频点对齐的分块砖墙式采样率转换算法，"
  "并给出了与之匹配的、可复现到 −300 dB 的测量方法。主要结论如下。")
p("(1) 把 P = M·s、Q = L·s 作为网格约束，可以使任意有理倍率的重采样退化为频域补零，"
  "误差只剩浮点舍入。九种倍率（含非整数、非 2 的幂、分母含 7）的零差深度为 300.9–303.8 dB。")
p("(2) 分块必须保证步进与上下文都是 M 的整数倍。修正前，44.1→56.448 kHz 的块模式零差只有 −2.5 dB，"
  "44.1→50.001 kHz 甚至出现 84.5 音分的移调；修正后全部倍率的块模式零差在 305.6 dB 以上，"
  "块长不小于文件长度时与整块处理逐位相同。")
p("(3) 文件首尾渐变窗的连续性阶数决定了升采样方向的精度天花板。"
  "把 C^2 的 smootherstep 换成 C^5 的多项式，40 音零差从 233.4 dB 提升到 302.6 dB，"
  "窗泄漏从 −259.8 dB 降到 −355.7 dB。这是本文最主要的定量发现。")
p("(4) 在统一口径下，Deep_PGGB 与 PGGB 的零差为 302.6 dB 与 302.0 dB，不可区分；"
  "Deep_PGGB 支持任意有理倍率而 PGGB 只支持整数倍率（请求 44.1→48 时它仍输出 4 倍样本）；"
  "速度上 Deep_PGGB 快 3.9 倍（118× 对 30×），并比最快的可转换引擎 r8brain-free（90×）快 1.3 倍。")
p("(5) 测量方法本身需要三条修正：整数相位参考、频率不随采样率缩放、增益迭代精修。"
  "第三条在对照实验中造成了 13 dB 的系统性偏差，足以把\"不可区分\"误判为\"领先 13 dB\"。")

