h1("3  测量方法")
h2("3.1  参考信号、增益与零差")
p("零差测试比较转换输出与解析参考。参考信号按 (f·n) mod f_s 递推相位，避免 sin(2πft) 在 18 kHz、4 s 时累积 4.5×10^5 rad 的相位误差；"
  "后者在 float64 下本身就是 −257 dBc，会把被测对象的地板误读成 217 dB。激励取 16 s，"
  "分析取 5 个互不重叠的 1 s 窗，取中位数。4 s 激励时 20 ms 渐变占 0.5%，边界效应会把读数压低 5–9 dB；"
  "16 s 把这一项降到 0.125%，单窗摆动则被中位数压住。")
p("增益估计必须迭代。闭式解 g=⟨a,b⟩/⟨b,b⟩ 的误差不是二阶的；对把峰值归一化到 0.99 的 PGGB，"
  "它把零差低估 13 dB（288.8 对 302.0 dB）。本文用三步 Gauss–Newton 精修，残差对增益的二阶项被吸收。"
  "另一个陷阱是测量区间：若在 4 s 全文件上估计增益，读数会比真实值低 0.5%（0.4975 对 0.5000），"
  "因为首尾各 20 ms 的渐变占 1% 时长、平均窗值为 0.5。把区间移到内部后，增益回到 1.000000。"
  "这个 0.5% 一度被误判为引擎的全局增益误差。")
p("零差定义为经增益精修后的参考与输出之差相对参考的比值：")
eq("D = 20 log10( ‖g·r − y‖ / ‖g·r‖ )", 3)
p("其中 r 为解析参考，y 为转换输出，g 由迭代得到。D 越大表示越接近参考；float64 的 FFT 舍入把 D 限制在 302 dB 附近。")

h2("3.2  失真产物的口径")
p("五项指标分别回答不同的问题。杂散取扣掉基频 bin 后的剩余能量，避免把矩形窗的泄漏裙边读成杂散；"
  "早期口径下 1 kHz 音的最差“杂散”落在 993 Hz，比真实值高 3 dB。镜像取镜像频率到输出奈奎斯特的带能量，"
  "分母用实测基频而不是固定 0.5；PGGB 的峰值归一化到 0.99，固定分母会凭空造出 6 dB。"
  "混叠用双音：96→44.1 kHz，1 kHz 参考音与 30 kHz 侵略音各 0.5 FS，读 44.1−30=14.1 kHz 的折叠 bin。"
  "只送孤立阻带音时，sox_ng 返回逐位全零，分母为 0，读数成了 −394 dBc；双音口径下它的真实值是 −221.0 dBc。")
p("互调用 CCIF（19/20 kHz）与 SMPTE（60 Hz/7 kHz，4:1）两组双音，归一化取两音电平的几何平均，"
  "避免过渡带削掉一个音时得到虚高的抑制比。多音用 24 个等幅音覆盖 100 Hz–18 kHz，取最差产物。"
  "所有指标以 dBc 表示[6]，即相对载波；分析地板则用同一激励下的理想引擎读数表示。")

h2("3.3  分析地板与灵敏度")
p("分析地板受 float64 的 FFT 舍入限制。本文测得：杂散 −307.1、镜像 −320.2、CCIF −334.4、SMPTE −334.7、"
  "多音 −295.2 dBc，零差约 302 dB。任何贴地板的读数都不应参与排序，因为换一个块长或激励，它会摆动 5–9 dB。")
p("地板之上还需要证明尺子本身。向输入注入 a3·x^3，a3 从 10^−3 降到 10^−6，三次谐波从 −86.6 降到 −146.6 dBc，"
  "每降一个数量级精确降 20 dB。更靠近地板的一步是直接注入探测音：−220 到 −310 dBc，"
  "测量值与注入值落在 1:1 线上；−310 dBc 处读数为 −308.8 dBc（图 2b）。"
  "这说明 −300 dBc 量级的读数是分辨出来的，不是外推的。")
p("图 2a 是 1 kHz、0.5 FS 单音经 44.1→88.2 kHz 转换后的输出频谱。去掉首尾各 100 ms 后，剩余 3.8 s 正好是 3800 个整周期，"
  "矩形窗没有泄漏，残余的积分电平为 −304.4 dBc。频谱上只有 1 kHz 的一根载波，其余是数值地板。")

