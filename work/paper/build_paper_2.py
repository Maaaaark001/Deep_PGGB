h1("4  测量方法")
p("当被测误差低到 −300 dB，测量方法本身成为主要的不确定度来源。本节给出五条规则，"
  "每一条都是先踩到坑、再验证出来的。")

h2("4.1  参考信号必须用整数相位")
p("参考信号写成 sin(2πf·n/f_s) 时，4 秒、18 kHz 的相位累积到 4.5×10^5 弧度，"
  "f·t 的相对误差 10^-16 变成绝对相位误差 4.5×10^-11 弧度，即 −217 dB。"
  "这个数字与被测引擎的误差同量级，于是\"测量\"变成了\"测自己\"。")
p("正确做法是利用 f 为整数 Hz、采样率为整数这一事实，用整数运算递推相位：")
cap("k = (round(f) · n) mod f_s，  参考 = Σ a_i · sin(2π·k/f_s + φ_i)。")
p("k/f_s 在 [0,1) 内精确可表示到 2^-53，相位不再累积误差。用这一口径重测，"
  "Deep_PGGB 的 44.1→176.4 零差从 216.8 dB 提升到 302.6 dB——不是引擎变好了，是尺子变准了。")

h2("4.2  参考频率不随采样率缩放")
p("重采样改变的是采样率，不是频率。一段 1 kHz 的音，升到 176.4 kHz 后仍然是 1 kHz。"
  "早期脚本把参考频率按目标/源采样率缩放（f·f_d/f_s），得到的是完全不同的信号，"
  "零差读出 0.0 dB——看起来\"完美\"，实际是废数据。现在脚本里有一行断言 null_db > 150 dB，"
  "让这类错误立刻炸出来，而不是安静地产生一个漂亮的数字。")

h2("4.3  增益必须迭代精修")
p("零差测试允许一个整体增益因子 g（因为不同引擎的归一化不同）。闭式最小二乘解是 g = <a,b>/<b,b>，"
  "它只精确到几个 ulp，而它的误差不是二阶的：残差中会出现 10^-15·|g·b| 量级的项。"
  "当 |g| = 1 时这一项几乎不可见；当 |g| = 1.11（PGGB 归一化到满刻度）时，它把零差压到 288.8 dB。")
p("用三步 Gauss-Newton 精修 g（g ← g + <d,b>/<b,b>，d = a − g·b）即可消除该伪影："
  "PGGB 的读数从 288.8 dB 变成 302.0 dB，Deep_PGGB 从 302.5 dB 变成 302.6 dB。"
  "这个 13 dB 的差异完全是估计算子的性质，与引擎无关。"
  "本文最初的对照实验正是在这里出了错：我们一度认为 Deep_PGGB 在升采样方向比 PGGB 低 70 dB，"
  "其中 13 dB 来自这里，另外 57 dB 来自 3.3 节所述的窗形。")

h2("4.4  分析窗必须居中，且必须掐掉边界")
p("所有频谱测量都在输出文件中央取窗。原因是引擎在文件首尾有渐变，渐变是幅度调制，"
  "会在基频两侧摊出裙边；从中间往后取的窗口，只要长度接近文件长度就已经贴到末尾。"
  "本文的早期实现因此把 −247 dB 误测成 −27 dB。")
p("零差测试比较的是两条处理链，不只是两个滤波器，因此必须先掐掉两端各 0.1 秒再比。"
  "同一对引擎（Deep_PGGB vs r8brain）不掐边时零差只有 26.9 dB，掐边后为 41.9 dB，"
  "而可闻带（<20 kHz）的差异是 −203 dB——剩下的差异全部来自 21–23 kHz 的过渡带设计不同。"
  "判级因此用可闻带深度，全带值只作为参考报出。")

h2("4.5  五项失真指标与它们各自的地板")
p("除零差外，本文用五项指标刻画非线性与杂散：单音杂散、上行镜像、下行混叠、"
  "互调（CCIF 与 SMPTE 两种双音）、24 音残余。前三项的读法都有陷阱，本节逐项说明口径，"
  "并在最后给出每项的分析地板。")
p("**单音杂散不能用单根谱线口径。** 早期实现取 20 Hz–20 kHz 内除基频 ±3 bin 之外的最强谱线。"
  "问题在于基频自身的窗泄漏裙边恰好落在 ±3 bin 之外的第一根谱线上："
  "实测 Deep_PGGB 因此读 −320.2 dBc，而把排除带从 ±3 bin 放宽到 ±50 bin 后变成 −321.0 dBc，"
  "PGGB 在两种口径下则都是 −323.1 dBc —— 表面上 3 dB 的差距全部来自泄漏，不是杂散。"
  "本文改用**泄漏免疫口径**：扣掉基频所在 bin 后的残余能量。"
  "因为每个音精确落在整秒窗的频点上，bin 值本身就是该音的复幅度，"
  "所以\"扣掉这些 bin\"等价于对基频做一次幅度/相位自由的最小二乘拟合并相减，"
  "结果对群延迟与通带下垂免疫，只对新长出来的频率成分敏感。")
p("**镜像用带能量，不用单根谱线。** 上采样的镜像产物是镜像频率附近的一整片，不是一根干净的线；"
  "只读一根 bin 会把\"产物落在别处\"误判成\"没有产物\"。本文统计从镜像频率到输出奈奎斯特的"
  "整段能量，参考取**输出里基频的实测电平**而不是输入幅度 —— 这一点在对比 PGGB 时是必需的，"
  "因为该内核把输出峰值归一化到 0.99，用固定 0.5 作分母会凭空多出约 6 dB。")
p("**混叠必须有通带参考音在场。** 这是本文发现的最严重的一处口径错误。"
  "早期实现只送一个 30 kHz 的阻带单音、再除以固定常数 0.5 作分母。"
  "可是把阻带真的清零的引擎（sox_ng 即如此，其输出 44100 个样本逐位全为 0）"
  "会让分子与分母同时趋于零，读数落到数值下限 EPS 上，得到一个 −394 dBc 的\"完美\"成绩。"
  "本文改为**双音口径**：1 kHz 参考音与 30 kHz 侵略音同时以 0.5 幅度送入，"
  "读折叠频率（44.1 kHz 输出下为 14.1 kHz）处相对参考音的电平。"
  "同一台 sox_ng 在双音口径下读 −221.0 dBc，从\"全场最强\"变成倒数第三。")
p("互调失真沿用两项标准双音：CCIF 为 19 kHz + 20 kHz 各 0.25 幅度，测 2f1−f2、2f2−f1、f2−f1、f1+f2；"
  "SMPTE 为 60 Hz（0.40）+ 7 kHz（0.10），测 7 kHz ± 60、±120 Hz 边带。"
  "多音残余为 24 个对数等间隔、Schroeder 相位的正弦（100 Hz–18 kHz，峰值 0.9），"
  "扣掉各音所在 bin 后的剩余能量相对音总能量。")
p("五项指标的地板由\"把同一组频率直接在目标采样率上合成、完全不经过重采样\"定出："
  "单音杂散 −307.1 dBc、镜像带能量 −320.2 dBc、CCIF −334.4 dBc、SMPTE −334.7 dBc、"
  "24 音残余 −295.2 dBc（零差另有一处约 302 dB 的地板）。"
  "这些数字是 float64 的 FFT 舍入，不是任何引擎的性质。因此："
  "贴在地板上的读数只说明\"低于测量能力\"，同时贴在地板上的两台引擎之间"
  "几个 dB 的差没有意义；只有明显高于地板的读数（r8brain −209.7、sox_ng −180.6、"
  "SciPy −65.0）才是真实失真。")
p("地板本身也随激励的相位精度变化，这一点值得单独强调。用 sin(2πf·n/f_s) 生成激励时，"
  "4 秒、88.2 kHz 的相位累积误差会把单音杂散的地板压在 −257 dBc，把多音残余压在 −225.3 dBc——"
  "于是 Deep_PGGB 的 −320 dBc 与 r8brain 的 −211 dBc 都被削到同一根线上，"
  "看起来\"两者差不多\"。改用 4.1 节的整数相位后，同样的引擎、同样的分析窗，"
  "读数才回到各自的真实值。这条经验对任何低于 −250 dB 的测量都成立："
  "先证明尺子比被测对象准，否则测的是尺子。")

h2("4.6  口径的依据，与两个会自欺的失效模式")
p("上述口径并非本文自创。公开的采样率转换器对照实验（InfiniteWave，由 Weiss Engineering、"
  "Alexey Lukin 与 Glenn Meadows 母带论坛的工程师共同设计）在 96→44.1 kHz 这一\"困难\"的"
  "分数倍率下，用四类信号评价转换器：0–48 kHz 扫频（看非线性与混叠）、"
  "1 kHz 单音（看谐波与量化噪声）、脉冲串（重建通带频响）、以及同一脉冲串给出的过渡带。")
p("其中两点直接决定了本文的口径选择。其一，**它测混叠靠的是扫频，而不是孤立的阻带单音**："
  "扫频在 5.5 秒之后越过 22 kHz，理想情况下应当被低通完全抑制，"
  "谱图上出现的任何能量都是混叠。孤立的阻带单音之所以不可靠，正是因为\"全部抑制\"与"
  "\"数值下溢\"在读数上无法区分——4.5 节 sox_ng 的 0/0 就是这一点的极端例子。"
  "其二，**它的倍率固定在 96→44.1**，分数倍率是最难的情形，也是各引擎差异最大的地方。")
p("在表述习惯上，本文遵循 AES17 对数字音频测量的约定：电平以 dBFS 表示（相对满刻度正弦），"
  "失真产物以 dBc 表示（相对载波），并用\"分析地板\"而不是\"本底噪声\"来指称测量系统的极限，"
  "以免与设备噪声混淆。本文不声称复现了 AES17 的任何一项具体测量，只采用其电平与产物的表述约定。")
p("由此可以总结出两个失效模式，它们都表现为\"读数好得不像话\"："
  "**其一是除以零**（孤立阻带音遇到真正清零的引擎，读数落到数值下限）；"
  "**其二是把尺子的误差读成被测对象的误差**（单 bin 口径读到基频的窗泄漏裙边、"
  "非整数相位激励自带的 −257 dBc 杂散）。两者的共同特征是：一旦出现，"
  "所有参与比较的引擎都会挤到同一根线上，而\"同一根线\"恰恰是测量体系失效的典型征兆。")
