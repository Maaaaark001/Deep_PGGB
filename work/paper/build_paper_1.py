h1("3  算法")
h2("3.1  精确有理倍率与频点对齐")
p("设输入采样率为 f_s、输出为 f_d，二者之比约化为互质的 L/M（例如 44100→48000 为 147/160，"
  "44100→176400 为 4/1，44100→50001 为 2100/2381）。取光滑数 s（只含因子 2、3、5），令")
cap("P = M·s，  Q = L·s，  则 Q/P = L/M 精确成立。")
p("在长度 P 的输入块上做实数到复数 FFT，得到 P/2+1 个非负频率 bin，"
  "其第 k 个 bin 对应频率 k·f_s/P；在长度 Q 的输出块上做逆变换，第 k 个 bin 对应 k·f_d/Q。"
  "由 Q/P = L/M 可得 f_d/Q = f_s/P，即两个网格的间距完全相同。"
  "于是\"插值\"就是：保留 min(nc_in, nc_out) 个 bin，其余清零，再做逆变换并除以 P 归一化。")
p("这一步没有任何近似。s 的选择只影响速度：s 越小，FFT 越短，但必须保证 M·s 与 L·s 都足够光滑，"
  "否则 FFT 会退化到 Bluestein 算法。实现中从 1 开始搜索最小的 s，使 M·s 与 L·s 都不含大于 5 的质因子。"
  "需要强调的是，把 s 限制为 2 的幂（早期实现的做法）会让网格点数被抬高到下一个 2 的幂，"
  "在 0.5 秒块、44.1 kHz 的情形下浪费 71% 的计算量，而精度一分不增——因为比例只由 L/M 决定。")
p("实测表明，把 7 也纳入光滑因子集合反而更慢：FFTW 对 radix-7 没有手工优化，"
  "7-smooth 的 22050 点变换比 2 的幂的 37632 点还慢。因此实现只接受 2、3、5。")

h2("3.2  分块与上下文")
p("把信号切成固定长度的块，每块取 [T 上下文][kept][T 上下文] 的结构，块外补零，"
  "变换后只保留中间 kept 段。上下文的作用是让每块的滤波器尾巴在块内完成，"
  "而不是被块边界截断后卷绕回来。")
p("这里有两个必须同时满足的整除条件，它们是本文修正的第一个真实缺陷：")
p("(1) 步进 kept 必须是 M 的整数倍。若 kept 不是 M 的倍数，相邻块在输出网格上的起点"
  "相差一个非整数输出样本，每个接缝都会出现相位台阶。实测中，44.1→56.448 kHz（L/M = 32/25）"
  "在块模式下对整块模式的零差只有 −2.5 dB，相位每块漂移 40–53°；44.1→50.001 kHz 更差，"
  "因为 P 不再是 M 的倍数，Q/P 偏离 L/M，音高被移动 84.5 音分（1 kHz 变成 1050 Hz）。")
p("(2) 上下文 T 也必须是 M 的整数倍。否则 lo = round(T·L/M)、hi = round((P−T)·L/M)、"
  "o0 = start·L/M 三处各自取整，误差逐块累积。")
p("修正后的实现把 T 向上吸附到 M 的整数倍（且 T ≥ M），文件过短时按 n/4 再向下吸附，"
  "内存不足时按 max_pts/4 吸附；当 P < 4T 时用光滑数搜索重新取 P，保证 kept = P − 2T 仍是 M 的倍数；"
  "并加入运行时断言 kept % M == 0。修正后，全部九种倍率的块模式对整块模式零差为 −248.8 至 −306.3 dB，"
  "块长 0.1/0.25/1.0 秒的音高全部精确为 1000.00 Hz（0 音分）。")
p("当块长不小于文件长度时，分块路径退化为整块路径，两者输出逐位相同——这一点在结果中作为"
  "\"块不变性\"被单独测量。")

h2("3.3  边界处理：渐变窗的阶数是精度的天花板")
p("文件边界是阶跃。理想低通对阶跃的响应是 sinc 型旁瓣，按 1/d 衰减，铺满整首曲子。"
  "加渐变窗可以把阶跃变成平滑过渡，从而压制旁瓣；但渐变窗本身是一个乘法器，"
  "它把信号频谱与窗自身的变换做卷积，于是产生了新的旁瓣。")
p("关键观察是：新旁瓣的电平由窗的连续性阶数决定，而不是由窗的长度决定。"
  "设窗为 w(t)，t ∈ [0,1]。若 w 在两端只有 C^1 连续（例如升余弦），其傅里叶变换按 d^-2 衰减；"
  "若达到 C^2（smootherstep，即 6t^5−15t^4+10t^3），按 d^-3 衰减；"
  "推广到 C^N，按 d^-(N+1) 衰减。")
p("本文采用的形式是 N 阶光滑阶跃多项式：")
cap("w(t) = t^(N+1) · Σ_{k=0..N} C(N+k, k) · C(2N+1, N−k) · (−t)^k，  t ∈ [0, 1]，w(1−t) 由对称性给出。")
p("N = 2 即传统的 smootherstep，N = 1 即 t^2(3−2t)（C^1），N = 4/5/6 是本文新增的选项。"
  "实现上，t > 0.5 时用 w(t) = 1 − w(1−t) 的镜像求值，因为直接对 t ≈ 1 求值会因大数相消丢失约 7 位有效数字"
  "——而丢失的恰好就是要压制的泄漏。")
p("把 15 kHz 单音乘以 20 ms 的窗，读 22.05 kHz 处的电平（参考信号在那里是零），得到窗泄漏：")
tbl([["窗形", "阶数", "22.05 kHz 泄漏 (dB)", "15 kHz 零差 (dB)", "40 音零差 (dB)"],
     ["cos", "C1", "−215.6", "205.4", "207.9"],
     ["smooth2（旧默认）", "C2", "−259.8", "247.9", "233.4"],
     ["smooth4", "C4", "−329.9", "305.8", "293.9"],
     ["smooth5（新默认）", "C5", "−355.7", "306.0", "302.6"],
     ["smooth6", "C6", "−376.9", "306.0", "302.6"]],
    "表 1  渐变窗阶数与残留。泄漏越低，落在源奈奎斯特上的残留越少，40 音零差越高。C5 之后收益饱和。",
    widths=[150, 60, 150, 120, 120])
p("表 1 解释了此前一个长期存在的困惑：为什么 Deep_PGGB 在降采样方向能达到 302 dB，"
  "在升采样方向却只有 233 dB。原因是升采样时输出网格比输入网格密，"
  "源奈奎斯特（22.05 kHz）在输出侧变成一个真实存在的频点，而窗泄漏正好落在那里；"
  "降采样时该频点被丢弃，泄漏随之消失。这也解释了为什么残差 100% 集中在 22.05 kHz 一根线上，"
  "而不是分布在可闻带内。")
p("一个容易被误判的细节：N = 6 的泄漏更低（−376.9 dB）但零差不再提升（302.6 dB，"
  "与 N = 5 的 302.6 dB 完全相同），因为此时限制因素已从窗泄漏转为 float64 的舍入。"
  "选 N = 5 作为默认值，是因为它在 15 kHz 处仍有 306.0 dB 的余量，而 N = 6 的额外代价（多两次多项式求值）"
  "换不回任何可测的收益。")
p("需要如实说明的边界：在距离源奈奎斯特 100 Hz 以内，任何渐变窗都会主导误差。"
  "21.9 kHz 处零差为 138.6 dB、21.95 kHz 为 82.3 dB、22 kHz 为 57.6 dB。"
  "这不是缺陷，而是\"把有限长片段当无限长信号\"的物理后果——PGGB 在同一位置的读数是 79.2 dB 与 55.7 dB，"
  "两者同量级。任何声称在奈奎斯特处仍有 300 dB 精度的说法，都需要先说明参考信号是如何定义的。")
