h1("1  引言")
p("把一段 44.1 kHz 的录音升到 176.4 kHz，或者把 96 kHz 的素材降到 48 kHz，是音频处理链中最常见的操作之一。"
  "理想的重采样被定义为带限插值[14]：把离散序列视为连续带限信号的采样，在目标时刻重新取值。"
  "任何实际实现都只能逼近这个定义，逼近的方式决定了算法的性格与代价。")
p("多相 FIR 把插值核分解为 L 个相位，每个输出点只访问其中一个相位，计算量与滤波器长度成正比而与倍率无关，"
  "因此成为实时系统的默认选择[1,2,4]。sox_ng 的 rate、libsoxr、r8brain-free 与 SSRC 都属于这一类，"
  "差别在滤波器设计：Kaiser 窗、等波纹、最小二乘，以及过渡带宽度与阻带衰减之间的取舍。"
  "频域方法走另一条路：把整段信号变换到频域，补零或截断，再变换回来。PGGB 与本文的 Deep_PGGB 属于后者；"
  "scipy.signal.resample_poly 的接口相似，内核仍是多相 FIR[3]。")
p("频域方法有一个别的方法不具备的性质。若输入点数 P 与输出点数 Q 满足 Q/P=L/M，且 P、Q 落在同一组频点上，"
  "则重采样不需要插值：输出频谱就是输入频谱的补零或截断，误差只剩浮点舍入。"
  "困难在于 P、Q 必须同时是某个光滑数的倍数，而 L/M 又必须是精确的有理数；此外，整段变换的内存随长度线性增长，"
  "长文件必须分块。分块会引入接缝，接缝处的相位或幅度不连续会在频域铺成宽带噪声，恰好抵消频域方法的最大优点。")
p("文件边界是第二个误差源，而且更隐蔽。一段音乐在开头和结尾被硬切，切点上的值与导数都不连续；"
  "理想低通会把这两个阶跃摊成按 1/f 衰减的旁瓣，铺满整首曲子。常见的对策是在首尾加渐变窗，"
  "但渐变窗本身是乘法器，它的旁瓣会落在源奈奎斯特附近，成为升采样方向精度的天花板。"
  "本文证明这个天花板由窗的连续性阶数而不是长度决定：C2 的 smootherstep 把零差限制在 233.4 dB，"
  "C5 把它抬到 302.6 dB。")
p("第三个问题属于测量。当被测误差低到 −300 dBc，测量系统自身的误差必须先被量化：参考信号的相位累积、"
  "增益估计的偏差、窗函数的泄漏，甚至“分母从哪里来”，都会在这个量级上改变结论。"
  "本文在对照实验中先后遇到三次这类问题，其中一次让 PGGB 的零差被低估 13 dB，"
  "另一次让 sox_ng 的混叠抑制被读成 −394 dBc。")
p("本文的工作可以概括为四点。第一，给出任意有理倍率下的精确频域映射，并把分块步进与上下文约束到 M 的整数倍，"
  "使接缝在 float64 精度内消失。第二，指出边界渐变窗的连续性阶数决定升采样天花板，给出 C5 窗与 20 ms 长度的组合。"
  "第三，把同一内核扩展为流式实现：FIFO 累积输入，按滑窗复用内核，只输出核心区；"
  "稳态输出与离线整文件处理一致，长度不漂移。第四，建立一套可复现到 −310 dBc 的测量协议，"
  "并在同一协议下对照八台引擎。")

