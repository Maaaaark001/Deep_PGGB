def fig(src, c):
    path = os.path.join(ROOT, src)
    with open(path, "rb") as f:
        head = f.read(33)
    w0, h0 = struct.unpack(">II", head[16:24])
    w = min(602, int(round(w0 * 96.0 / 300.0 * 1.02)))
    h = int(round(w * h0 / float(w0)))
    B.append({"t": "fig", "src": src, "w": w, "h": h, "cap": c})


