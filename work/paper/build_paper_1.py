h1("2  方法")
h2("2.1  精确有理映射与频域补零")
p("设源采样率为 f_s，目标为 f_s′，二者之比写成既约分数 L/M。取光滑数 s=2^a·3^b·5^c，令 P=M·s、Q=L·s。"
  "于是 Q/P=L/M 精确成立，而 P、Q 都可以用混合基 FFT 处理[5]。输入的第 k 个频点对应频率 k·f_s/P，"
  "输出的第 k 个频点对应 k·f_s′/Q=k·f_s/(M·s)，两者是同一张频率网格。因此，频域重采样退化为一次补零或截断：")
eq("Y[k] = X[k]，0 ≤ k ≤ min(P, Q)/2", 1)
p("其余频点置零，并按共轭对称恢复负频率。逆变换后乘以 1/P，通带增益回到 1。对降采样，Q<P，高于 Q/2 的频点被丢弃；"
  "对升采样，Q>P，新频点置零。整个过程没有插值核，也没有过渡带设计，阻带抑制由频域截断的锐度决定。")
p("光滑数的选择只影响效率，不影响正确性。若 P、Q 含大素数因子，FFT 会退化到 Bluestein 算法，成本上升；"
  "把 s 取成 2、3、5 的乘积，可以在几乎不增加点数的前提下保持混合基 FFT。"
  "对 44.1→48 kHz，L/M=160/147，P=147s、Q=160s；对 44.1→50.001 kHz，L/M=2381/2100，"
  "P=2100s、Q=2381s，2381 是素数。后者的零差仍达到 300.9 dB，说明精度不依赖倍率的算术形式。")
p("输出幅度在内部区间严格等于输入幅度。若在整段文件上估计增益，4 s 测试会读到 0.4975 而不是 0.5000；"
  "这不是全局增益误差，而是首尾各 20 ms 的渐变占 1% 时长、平均窗值为 0.5 所致（3.1 节）。")

h2("2.2  分块、上下文与重叠保留")
p("分块采用重叠保留。第 b 块取输入区间 [b·C_in−C_ctx, (b+1)·C_in+C_ctx)，变换后只保留与核心区对应的输出，"
  "再把各块的核心区按序拼接。核心长度与上下文都取 M 的整数倍：C_in=M·c，C_out=L·c。"
  "这样每个块的频点相位与整段变换一致，块与块之间不会出现相位台阶。若步进不是 M 的整数倍，"
  "Q/P 仍在全局成立，但块内的网格相对整段偏移了一个分数 bin，接缝处会出现随块数累积的相位误差。")
p("上下文长度的作用有两个。对升采样，它要装下砖墙滤波器的时域尾巴，否则补零后的截断会在块边缘产生振铃；"
  "对降采样，它要装下抗混叠滤波器的尾巴。实测 800 ms 把镜像项从 −315.6 dBc 提高到 −319.0 dBc；"
  "继续加长收益递减，而内存与一次变换的长度线性增长。")
p("块长与速度、接缝是同一根旋钮的两端。0.5 s 块在双 worker 下达到 148.3×，16 s 块约 117.7×；"
  "但小块会把接缝周期缩短，SMPTE 边带上留下约 10 dB 的痕迹。默认取 16 s，是速度与接缝之间的折中。"
  "图 1a 给出离线路径的信号流。")

h2("2.3  边界、连续性阶数与 C5 渐变窗")
p("把长度 N 的信号乘以窗 w(n)，其频谱是原频谱与 W(f) 的卷积。若 w 在两端不连续，W(f) 的旁瓣按 1/f 衰减；"
  "若 w 的一阶导数也不连续，衰减仍是 1/f；直到第 k 阶导数连续，旁瓣才按 1/f^(k+1) 衰减[15]。"
  "升采样时，源奈奎斯特 f_s/2 正好落在输出通带的边缘，W(f) 的旁瓣在那里留下的残留不会被后续滤波去掉，"
  "因此它直接决定了零差的上限。")
p("本文采用镜像的 C5 smootherstep：")
eq("w(t) = S5(min(t, 1−t))，S5(u) = 6u^5 − 15u^4 + 10u^3", 2)
p("t>0.5 时取 1−w(1−t)，以避免大数相消。图 6a 给出不同阶数的泄漏与 40 音零差。"
  "C1 的余弦窗在 22.05 kHz 留下 −215.6 dBc，C2 改善到 −259.8 dBc，C4 到 −329.9 dBc，C5 到 −355.7 dBc；"
  "零差相应从 207.9 dB 升到 302.6 dB。C6 把泄漏再压低 21 dB，但零差停在 302.6 dB，收益被 float64 地板吸收。")
p("渐变窗长度取 20 ms[7]。更长的窗会吃掉素材本身，更短的窗使旁瓣变宽。20 ms 在 44.1 kHz 下是 882 点，"
  "对 16 s 块只占 0.55%。需要强调，渐变窗是文件边界的约定，不是块接缝的处理；"
  "块接缝由上下文与对齐的步进解决，两者在实现中已经解耦。")

h2("2.4  流式扩展：FIFO 与滑窗")
p("流式实现把同一内核包在一个 FIFO 前端之后。FIFO、游标与窗口拼接位于 C++ 引擎内，"
  "对外只暴露 dpggb_stream_create/push/flush/destroy 四个 C 入口；每次 push 把新样本追加到缓冲区，"
  "当缓冲区中至少有左上下文、一个核心和右上下文时，取窗、变换、只输出核心，然后游标前进一个核心长度。"
  "把状态放进引擎而不是脚本层，使线程局部的 FFT plan 能跨窗口复用，也避免每个窗口重新进入进程或临时文件；"
  "同一窗口几何下，这一改动把流式吞吐提高 3.5–4.1×（§4.7）。"
  "窗口之间保留重叠，但重叠只用于计算，不参与输出。早期版本在相邻核心之间做 cross-fade，"
  "结果把两个不重叠的时间区混在一起，4 s 测试的长度漂移达到 66918 帧，零差跌到 −3.4 dB；"
  "去掉 cross-fade 后漂移归零。")
p("头部有一个约定差异。第一个窗口没有左上下文，只能零填充；离线路径则在真实文件头做 20 ms 渐变。"
  "流式实现无法知道“这是文件头”，因此前 20 ms 的输出与离线不同。实测偏差在 20 ms 处降到 −78 dB，"
  "80 ms 后 −90 dB，之后进入稳态。把连续流的第一次 push 当作文件头，是使用者的选择，而不是算法的缺陷。"
  "图 1b 给出流式路径与窗口几何。")

