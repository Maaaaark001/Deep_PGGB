h1("1  引言")
p("把 44.1 kHz 的母带升到 176.4 kHz、或把 96 kHz 的录音降到 48 kHz，是音频工程里最常见的操作之一，"
  "也是被研究得最透彻的问题之一。理想的做法是理想的低通插值：把离散序列看作带限连续信号，"
  "在目标时刻重新取样。实际实现则在\"逼近理想\"与\"算得动\"之间做取舍，取舍的方式决定了引擎的性格。")
p("现有引擎可以按取舍方式分成三类。第一类是多相 FIR（polyphase FIR），把滤波器拆成 L 个相位、"
  "每个相位只算需要的输出点，复杂度与滤波器长度成正比而与倍率无关；sox_ng 的 rate 效果、"
  "libsoxr、r8brain-free、SSRC 都属于这一类，区别只在滤波器设计（Kaiser 窗、最小二乘、"
  "等波纹）与过渡带宽度的选择。第二类是频域方法，把信号变换到频域、补零或截断、再变换回来；"
  "scipy.signal.resample_poly 是时域实现，而 PGGB 与本文的 Deep_PGGB 属于频域实现。"
  "第三类是混合方法，例如 FFmpeg 的 aresample 可以挂 libsoxr 内核。")
p("频域方法有一个别的方法做不到的性质：当输出点数 Q 与输入点数 P 满足 Q/P = L/M 且 P、Q 都是"
  "同一个光滑数的倍数时，输出的每一个频点都精确对应输入的一个频点，"
  "\"重采样\"就退化成\"把高频 bin 清零\"。此时不存在插值核的近似，不存在过渡带的形状选择，"
  "误差只剩浮点运算的舍入。代价是必须整段变换，或者分块并处理接缝。")
p("分块是必须的：一首 5 分钟的 44.1 kHz 立体声母带是 1300 万点，4 倍升采样后是 5200 万点，"
  "单次 FFT 的中间数组就要几个 GB。但分块会引入接缝，接缝会引入周期性的相位与幅度不连续，"
  "而这些不连续在频域上表现为宽带噪声——恰好把频域方法最大的优点抵消掉。"
  "如何在分块的前提下保持\"整段变换\"的精度，是本文要回答的第一个问题。")
p("第二个问题更隐蔽：文件本身有边界。一段音乐在开头和结尾处被硬切，切点上的信号值与导数都不连续，"
  "理想低通会把这两个阶跃摊成按 1/d 衰减的旁瓣，铺满整首曲子。这不是算法错误，"
  "而是\"把有限长片段当作无限长信号处理\"的必然结果。常见的对策是在首尾加渐变窗，"
  "但渐变窗本身是幅度调制，它也会产生旁瓣——而旁瓣落在哪里，取决于窗的形状。"
  "本文证明：当渐变窗是 C^2 的 smootherstep 时，旁瓣在源奈奎斯特（22.05 kHz）附近留下的残留"
  "恰好成为升采样方向精度的天花板（233 dB）；把窗提升到 C^5，天花板抬到 303 dB。")
p("第三个问题是测量。当被测对象的误差已经低到 −300 dB，测量系统自身的误差就必须先被量化。"
  "本文给出三条实践规则：(i) 参考信号必须用整数相位递推生成，否则 18 kHz、4 秒的相位累积误差"
  "本身就是 −217 dB；(ii) 参考频率不随采样率缩放，重采样改变的是采样率而不是频率；"
  "(iii) 零差测试的增益必须用迭代精修而不是闭式解，否则归一化输出的引擎会被系统性低估十余 dB。"
  "第三条是本文在对照实验中发现的，它一度让我们误判 Deep_PGGB 比 PGGB 高 70 dB。")

